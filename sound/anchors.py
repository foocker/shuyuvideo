"""Turn named words in the narration into times the picture can use.

Usage: python sound/anchors.py <film-dir>

<film>/anchors.json maps a name to a line id and a word in that line:
  {"flip": {"line": "k2", "word": "倒过来"}, "rect": {"line": "k3", "at": "end"}}
`word` takes the start of that word (`nth` picks a later repeat, from 1);
`at` may be "start" or "end" of the whole line; `offset` adds seconds.
Writes <film>/assets/anchors.js (window.ANCHORS) and <film>/anchors.resolved.json.
"""
import json
import sys
from pathlib import Path


def resolve(timings, spec):
    line = next((l for l in timings['lines'] if l['id'] == spec['line']), None)
    if line is None:
        raise SystemExit(f"anchor names unknown line {spec['line']!r}")
    if 'word' in spec:
        hits = [w for w in line['words'] if w['text'] == spec['word']]
        nth = spec.get('nth', 1)
        if len(hits) < nth:
            words = ' '.join(w['text'] for w in line['words'])
            raise SystemExit(f"word {spec['word']!r} not found in {spec['line']}; words are: {words}")
        t = hits[nth - 1]['start']
    else:
        t = line['end'] if spec.get('at') == 'end' else line['start']
    return round(t + spec.get('offset', 0), 3)


def main(film):
    sys.stdout.reconfigure(encoding='utf-8')
    timings = json.loads((film / 'voice-timings.json').read_text(encoding='utf-8'))
    specs = json.loads((film / 'anchors.json').read_text(encoding='utf-8'))
    anchors = {name: resolve(timings, spec) for name, spec in specs.items()}
    anchors['end'] = timings['duration']
    (film / 'anchors.resolved.json').write_text(json.dumps(anchors, ensure_ascii=False, indent=2), encoding='utf-8')
    (film / 'assets').mkdir(exist_ok=True)
    (film / 'assets/anchors.js').write_text(
        '/* Generated by sound/anchors.py from voice-timings.json. Do not edit. */\n'
        f'window.ANCHORS = {json.dumps(anchors, ensure_ascii=False, indent=2)};\n', encoding='utf-8')
    for name, t in anchors.items():
        print(f'{name:>12} {t:8.3f}')


if __name__ == '__main__':
    main(Path(sys.argv[1]).resolve())
